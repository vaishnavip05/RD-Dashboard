  function loadReportsFromStorage() {
    try {
      var raw = localStorage.getItem(STORAGE_KEY);
      if (raw) {
        var parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) {
          MONTHLY_REPORTS = parsed;
        }
      }
    } catch (e) {
      console.warn('Could not load reports from localStorage', e);
    }
  }

  function saveReportsToStorage() {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(MONTHLY_REPORTS));
    } catch (e) {
      console.warn('Could not save reports to localStorage', e);
    }
  }

  function saveReport(reportObj) {
    if (!reportObj || !reportObj.id) return false;
    var idx = MONTHLY_REPORTS.findIndex(function (r) { return r.id === reportObj.id; });
    if (idx !== -1) {
      MONTHLY_REPORTS[idx] = reportObj;
    } else {
      MONTHLY_REPORTS.unshift(reportObj);
    }
    saveReportsToStorage();
    return true;
  }

